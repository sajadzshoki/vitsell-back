import vine from '@vinejs/vine'

export const platformSettingsValidator = vine.compile(
  vine.object({
    defaultLocale: vine.string().trim().optional(),
    currencyLabel: vine.string().trim().optional(),
    dateFormatHint: vine.string().trim().optional(),
    numberFormatHint: vine.string().trim().optional(),
    timezone: vine.string().trim().optional(),
    logoUrl: vine.string().trim().nullable().optional(),
    faviconUrl: vine.string().trim().nullable().optional(),
    defaultOgImage: vine.string().trim().nullable().optional(),
    brandName: vine.string().trim().optional(),
    brandDescription: vine.string().trim().optional(),
    supportPhone: vine.string().trim().optional(),
    salesPhone: vine.string().trim().optional(),
    supportEmail: vine.string().trim().optional(),
    address: vine.string().trim().optional(),
    workingHours: vine.string().trim().optional(),
    minOrderAmount: vine.number().min(0).optional(),
    guestCheckoutEnabled: vine.boolean().optional(),
    outOfStockBehavior: vine.enum(['hide', 'show_unavailable', 'allow_backorder'] as const).optional(),
    taxDisplay: vine.enum(['inclusive', 'exclusive', 'none'] as const).optional(),
    returnWindowDays: vine.number().min(0).optional(),
    cancelAllowedStatuses: vine.string().trim().optional(),
    notifyAdminNewOrder: vine.boolean().optional(),
    notifyAdminFailedPayment: vine.boolean().optional(),
    notifyAdminLowStock: vine.boolean().optional(),
    notifyAdminReturn: vine.boolean().optional(),
    notifyAdminRefund: vine.boolean().optional(),
    notifyCustomerOrderStatus: vine.boolean().optional(),
    notifyCustomerPayment: vine.boolean().optional(),
    notifyCustomerShipping: vine.boolean().optional(),
    notifyCustomerMarketing: vine.boolean().optional(),
    freeShippingThreshold: vine.number().min(0).optional(),
    deliveryEstimateText: vine.string().trim().optional(),
    shippingMethodsVisible: vine.boolean().optional(),
    onlinePaymentEnabled: vine.boolean().optional(),
    codPaymentEnabled: vine.boolean().optional(),
    installmentPaymentEnabled: vine.boolean().optional(),
    productCardStyle: vine.enum(['classic', 'showcase'] as const).optional(),
  })
)
